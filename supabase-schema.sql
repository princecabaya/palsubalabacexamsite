-- Exam Guard: Supabase schema
-- Run this in Supabase SQL Editor on a NEW project.
-- The GitHub Pages client uses only the publishable/anon key.
-- NEVER expose the service_role key in browser code.

create extension if not exists pgcrypto;

-- ---------- Core tables ----------
create table if not exists public.students (
  id uuid primary key default gen_random_uuid(),
  student_no text not null unique,
  full_name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.exams (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  title text not null,
  duration_minutes integer not null check (duration_minutes between 1 and 600),
  status text not null default 'draft' check (status in ('draft','published','closed')),
  start_at timestamptz,
  end_at timestamptz,
  archived boolean not null default false,
  archived_at timestamptz,
  created_at timestamptz not null default now()
);

-- Keep upgrades idempotent for projects created with an earlier schema.
alter table public.exams add column if not exists archived boolean not null default false;
alter table public.exams add column if not exists archived_at timestamptz;

create table if not exists public.questions (
  id uuid primary key default gen_random_uuid(),
  exam_id uuid not null references public.exams(id) on delete cascade,
  position integer not null,
  prompt text not null,
  question_type text not null default 'mcq' check (question_type in ('mcq','text')),
  choices jsonb,
  correct_answer text,
  points numeric(8,2) not null default 1,
  created_at timestamptz not null default now(),
  unique(exam_id, position)
);

create table if not exists public.attempts (
  id uuid primary key default gen_random_uuid(),
  attempt_token uuid not null unique default gen_random_uuid(),
  exam_id uuid not null references public.exams(id) on delete cascade,
  student_id uuid not null references public.students(id) on delete cascade,
  status text not null default 'active' check (status in ('active','submitted','expired')),
  started_at timestamptz not null default now(),
  submitted_at timestamptz,
  score numeric(10,2),
  max_score numeric(10,2),
  user_agent text,
  unique(exam_id, student_id)
);

create table if not exists public.responses (
  attempt_id uuid not null references public.attempts(id) on delete cascade,
  question_id uuid not null references public.questions(id) on delete cascade,
  answer text,
  saved_at timestamptz not null default now(),
  primary key(attempt_id, question_id)
);

create table if not exists public.proctor_events (
  id bigint generated by default as identity primary key,
  attempt_id uuid not null references public.attempts(id) on delete cascade,
  event_type text not null,
  details jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create index if not exists proctor_events_attempt_time_idx
  on public.proctor_events(attempt_id, occurred_at desc);

-- ---------- Teacher/admin auth ----------
create table if not exists public.exam_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.exam_guard_handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.exam_admins(user_id) values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists exam_guard_on_auth_user_created on auth.users;
create trigger exam_guard_on_auth_user_created
after insert on auth.users
for each row execute function public.exam_guard_handle_new_auth_user();

create or replace function public.exam_guard_current_user_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(
    select 1 from public.exam_admins
    where user_id = auth.uid() and is_admin = true
  );
$$;

