-- Normalize student identifiers for tolerant matching.
create or replace function public.exam_guard_normalize_student_no(p_value text)
returns text
language sql
immutable
as $norm$
  select regexp_replace(lower(coalesce(p_value,'')), '[^a-z0-9]', '', 'g');
$norm$;

create or replace function public.exam_guard_normalize_name(p_value text)
returns text
language sql
immutable
as $norm$
  select regexp_replace(lower(coalesce(p_value,'')), '[^a-z0-9]', '', 'g');
$norm$;


-- ---------- Student identity preview before exam start ----------
create or replace function public.preview_exam_identity(
  p_exam_code text,
  p_student_no text
)
returns table(
  exam_title text,
  student_name text,
  student_no text
)
language plpgsql
security definer
set search_path = public
as $identity$
declare
  v_exam public.exams%rowtype;
  v_student public.students%rowtype;
begin
  select * into v_exam
  from public.exams
  where lower(code) = lower(trim(p_exam_code))
    and status = 'published'
    and coalesce(archived, false) = false;

  if not found then
    raise exception 'Exam code is invalid or the exam is not published.';
  end if;

  if v_exam.start_at is not null and now() < v_exam.start_at then
    raise exception 'This exam has not opened yet.';
  end if;

  if v_exam.end_at is not null and now() > v_exam.end_at then
    raise exception 'This exam is already closed.';
  end if;

  select s.* into v_student
  from public.students s
  where public.exam_guard_normalize_student_no(s.student_no)
        = public.exam_guard_normalize_student_no(p_student_no)
    and s.active = true
  limit 1;

  if not found then
    raise exception 'Student ID does not match an active student record.';
  end if;

  return query
  select v_exam.title, v_student.full_name, v_student.student_no;
end;
$identity$;

revoke all on function public.preview_exam_identity(text,text) from public;
grant execute on function public.preview_exam_identity(text,text) to anon, authenticated;

-- ---------- Student RPC API ----------
create or replace function public.start_exam(
  p_exam_code text,
  p_student_no text,
  p_user_agent text default null
)
returns table(
  attempt_token uuid,
  exam_title text,
  student_name text,
  student_no text,
  started_at timestamptz,
  ends_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_exam public.exams%rowtype;
  v_student public.students%rowtype;
  v_attempt public.attempts%rowtype;
begin
  select * into v_exam
  from public.exams
  where lower(code) = lower(trim(p_exam_code))
    and status = 'published'
    and coalesce(archived, false) = false;

  if not found then
    raise exception 'Exam code is invalid or the exam is not published.';
  end if;

  if v_exam.start_at is not null and now() < v_exam.start_at then
    raise exception 'This exam has not opened yet.';
  end if;

  if v_exam.end_at is not null and now() > v_exam.end_at then
    raise exception 'This exam is already closed.';
  end if;

  select s.* into v_student
  from public.students as s
  where public.exam_guard_normalize_student_no(s.student_no)
        = public.exam_guard_normalize_student_no(p_student_no)
    and s.active = true;

  if not found then
    raise exception 'Student ID does not match an active student record.';
  end if;

  select * into v_attempt
  from public.attempts
  where exam_id = v_exam.id and student_id = v_student.id;

  if found then
    if v_attempt.status = 'submitted' then
      raise exception 'This student has already submitted this exam.';
    end if;

    if now() > v_attempt.started_at + make_interval(mins => v_exam.duration_minutes) then
      update public.attempts
      set status = 'expired'
      where id = v_attempt.id;
      raise exception 'The existing exam attempt has expired.';
    end if;
  else
    insert into public.attempts(exam_id, student_id, user_agent)
    values(v_exam.id, v_student.id, left(p_user_agent, 2000))
    returning * into v_attempt;
  end if;

  return query
  select
    v_attempt.attempt_token,
    v_exam.title,
    v_student.full_name,
    v_student.student_no,
    v_attempt.started_at,
    least(
      v_attempt.started_at + make_interval(mins => v_exam.duration_minutes),
      coalesce(v_exam.end_at, 'infinity'::timestamptz)
    );
end;
$$;


-- ---------- Active attempt recovery ----------
create or replace function public.resume_exam(p_attempt_token uuid)
returns table(
  attempt_token uuid,
  exam_title text,
  student_name text,
  student_no text,
  started_at timestamptz,
  ends_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $resume$
declare
  v_attempt public.attempts%rowtype;
  v_exam public.exams%rowtype;
  v_student public.students%rowtype;
  v_ends_at timestamptz;
begin
  select * into v_attempt
  from public.attempts
  where attempts.attempt_token = p_attempt_token;

  if not found or v_attempt.status <> 'active' then
    raise exception 'No active exam session was found.';
  end if;

  select * into v_exam from public.exams where id = v_attempt.exam_id;
  select * into v_student from public.students where id = v_attempt.student_id;

  v_ends_at := least(
    v_attempt.started_at + make_interval(mins => v_exam.duration_minutes),
    coalesce(v_exam.end_at, 'infinity'::timestamptz)
  );

  if now() > v_ends_at then
    update public.attempts
    set status = 'expired'
    where id = v_attempt.id;

    raise exception 'The saved exam session has expired.';
  end if;

  return query
  select
    v_attempt.attempt_token,
    v_exam.title,
    v_student.full_name,
    v_student.student_no,
    v_attempt.started_at,
    v_ends_at;
end;
$resume$;

create or replace function public.get_saved_exam_responses(p_attempt_token uuid)
returns table(
  question_id uuid,
  answer text,
  saved_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $resume$
declare
  v_attempt public.attempts%rowtype;
  v_exam public.exams%rowtype;
begin
  select * into v_attempt
  from public.attempts
  where attempts.attempt_token = p_attempt_token;

  if not found or v_attempt.status <> 'active' then
    raise exception 'No active exam session was found.';
  end if;

  select * into v_exam from public.exams where id = v_attempt.exam_id;

  if now() > least(
    v_attempt.started_at + make_interval(mins => v_exam.duration_minutes),
    coalesce(v_exam.end_at, 'infinity'::timestamptz)
  ) then
    update public.attempts
    set status = 'expired'
    where id = v_attempt.id;

    raise exception 'The saved exam session has expired.';
  end if;

  return query
  select r.question_id, r.answer, r.saved_at
  from public.responses r
  where r.attempt_id = v_attempt.id
  order by r.saved_at;
end;
$resume$;

